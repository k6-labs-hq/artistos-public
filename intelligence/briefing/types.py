"""Type definitions for briefing system."""

from dataclasses import dataclass, field
from datetime import datetime
from typing import Any


@dataclass
class BriefingMetrics:
    """Metrics for a specific domain."""

    total_count: int
    period_change: float  # percentage change
    notable_events: list[str] = field(default_factory=list)
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class BriefingSection:
    """Single section of the weekly briefing."""

    title: str
    summary: str
    metrics: dict[str, BriefingMetrics] | None = None
    recommendations: list[str] = field(default_factory=list)
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class BriefingData:
    """Complete weekly briefing data."""

    week_start: datetime
    week_end: datetime
    sections: list[BriefingSection]
    generated_at: datetime = field(default_factory=datetime.now)
    generated_by: str = "XR7 Intelligence System"

    def to_markdown(self) -> str:
        """Generate markdown report."""
        lines = [
            f"# XR7 Weekly Intelligence Briefing",
            f"",
            f"**Week:** {self.week_start.strftime('%Y-%m-%d')} to {self.week_end.strftime('%Y-%m-%d')}  ",
            f"**Generated:** {self.generated_at.strftime('%Y-%m-%d %H:%M:%S')} UTC  ",
            f"**Generated By:** {self.generated_by}",
            f"",
            "---",
            "",
        ]

        for section in self.sections:
            lines.append(f"## {section.title}")
            lines.append("")
            lines.append(section.summary)
            lines.append("")

            if section.metrics:
                lines.append("### Key Metrics")
                lines.append("")
                for metric_name, metric in section.metrics.items():
                    change_indicator = "↑" if metric.period_change > 0 else "↓" if metric.period_change < 0 else "→"
                    lines.append(
                        f"- **{metric_name}**: {metric.total_count} ({change_indicator} {abs(metric.period_change):.1f}%)"
                    )
                lines.append("")

            if section.recommendations:
                lines.append("### Recommendations")
                lines.append("")
                for rec in section.recommendations:
                    lines.append(f"- {rec}")
                lines.append("")

            lines.append("---")
            lines.append("")

        return "\n".join(lines)
